// Kurzer, eindeutiger Name für ein Wort: ohne Artikel, ohne Akzente.
// "la città" → "citta", "l'acqua" → "acqua", "a destra" → "a-destra"
function wortId(it) {
  return it
    .toLowerCase()
    .replace(/^(il|lo|la|i|gli|le|un|uno|una) /, '')
    .replace(/^(l|un)'/, '')
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/['?!]/g, '')
    .trim()
    .replace(/\s+/g, '-');
}

// Reihenfolge für neue Wörter: Stufe für Stufe, darin abwechselnd aus jedem Thema.
const WORTSCHATZ = (() => {
  const liste = [];
  for (const stufe of ['A1', 'A2', 'B1', 'B2']) {
    const themen = WORTSCHATZ_THEMEN.filter((t) => t.stufe === stufe);
    if (!themen.length) continue;
    const laengste = Math.max(...themen.map((t) => t.woerter.length));
    for (let i = 0; i < laengste; i++) {
      for (const t of themen) {
        const w = t.woerter[i];
        if (!w) continue;
        const [it, de, auch] = w;
        liste.push({ id: wortId(it), it, de, auch, thema: t.thema, stufe });
      }
    }
  }
  return liste;
})();
